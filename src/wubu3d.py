def perf_at(c, f):
    """the same keyed performance the preview uses, sampled for Blender"""
    keys = sorted(c.get("perf") or [], key=lambda k: k["f"])
    if not keys:
        return {}
    if f <= keys[0]["f"]:
        return {k: v for k, v in keys[0].items() if k != "f"}
    if f >= keys[-1]["f"]:
        return {k: v for k, v in keys[-1].items() if k != "f"}
    for i in range(len(keys) - 1):
        a, b = keys[i], keys[i + 1]
        if a["f"] <= f <= b["f"]:
            t = (f - a["f"]) / max(1, b["f"] - a["f"])
            t = t * t * (3 - 2 * t)
            out = {}
            for k in set(a) | set(b):
                if k == "f":
                    continue
                va = float(a.get(k, b.get(k, 0.0)))
                vb = float(b.get(k, a.get(k, 0.0)))
                out[k] = va + (vb - va) * t
            return out
    return {}


def perform(rig, parts, c, f0, f1, path, holds):
    """Bake the acting track onto the rig every second frame.

    A walk cycle is a loop; a performance is a set of choices — where he stops, how far
    he bends to set the lamp down, how long he holds it, when he looks back. Those are
    keyed here, eased between, and baked so the render is deterministic.
    """
    body, head, hood, coat, legL, legR, armL, armR = parts
    span = max(1, f1 - f0)
    for f in range(f0, f1 + 1, 2):
        p = perf_at(c, f)
        shift = 0.0
        for (a, b) in holds:
            if f >= b:
                shift += b - a
            elif f > a:
                shift += f - a
        t = max(0.0, min(1.0, (f - shift - f0) / span))
        px = path[0][0] + (path[1][0] - path[0][0]) * t
        py = path[0][1] + (path[1][1] - path[0][1]) * t
        crouch = float(p.get("crouch", 0.0))
        pitch = float(p.get("pitch", 0.0))
        walkp = float(p.get("walk", 1.0))
        rig.location = (px, py, -crouch)
        rig.keyframe_insert("location", frame=f)
        for ob, k in ((body, 1.0), (coat, 0.85), (head, 0.55), (hood, 0.55)):
            ob.rotation_euler = (pitch * k, 0.0, float(p.get("head", 0.0)) * (0.6 if ob in (head, hood) else 0.0))
            ob.keyframe_insert("rotation_euler", frame=f)
        ph = 2 * math.pi * ((f - shift - f0) / max(4.0, span / 9.0))
        legL.rotation_euler = (math.radians(24) * math.sin(ph) * walkp - crouch * 1.5, 0, 0)
        legR.rotation_euler = (-math.radians(24) * math.sin(ph) * walkp - crouch * 1.5, 0, 0)
        armL.rotation_euler = (math.radians(-13) * math.sin(ph) * walkp, 0, 0)
        armR.rotation_euler = (float(p.get("arm_r", math.radians(-18))), 0, 0)
        for ob in (legL, legR, armL, armR):
            ob.keyframe_insert("rotation_euler", frame=f)




