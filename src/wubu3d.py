def load_spec(path: Path) -> dict:
    """Read and resolve a spec. An invalid spec never reaches a renderer."""
    raw = json.loads(path.read_text())
    errs, warns = wubu3d_spec.validate(raw)
    for w in warns:
        print(f"[wubu3d] spec warning {w['path']}: {w['message']}")
    if errs:
        for e in errs:
            print(f"[wubu3d] spec error {e['path']}: {e['message']}", file=sys.stderr)
        print(f"[wubu3d] {path}: {len(errs)} error(s) — nothing was rendered; "
              f"run `wubu3d.py validate {path}`", file=sys.stderr)
        raise SystemExit(2)
    return wubu3d_spec.resolve(raw, DEFAULTS, PRESETS)

