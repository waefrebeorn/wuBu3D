def animate_bones(rig, c, f0, f1, holds, path):
    span = max(1, f1 - f0)
    for f in range(f0, f1 + 1, 2):
        p = perf_at(c, f)
        shift = 0.0
        for (a, b) in holds:
            if f >= b:
                shift += b - a
            elif f > a:
                shift += f - a
        t = max(0.0, min(1.0, (f - shift - f0) / span))
        walkp = float(p.get("walk", 1.0))
        crouch = float(p.get("crouch", 0.0))
        pitch = float(p.get("pitch", 0.0))
        ph = 2 * math.pi * ((f - shift - f0) / max(4.0, span / 9.0))
        rig.location = (path[0][0] + (path[1][0] - path[0][0]) * t,
                        path[0][1] + (path[1][1] - path[0][1]) * t, 0.0)
        rig.keyframe_insert("location", frame=f)
        pb = rig.pose.bones

        def key(name, rx=0.0, rz=0.0):
            b = pb.get(name)
            if b is None:
                return
            b.rotation_mode = 'XYZ'
            b.rotation_euler = (rx, 0.0, rz)
            b.keyframe_insert("rotation_euler", frame=f)

        key('pelvis', -crouch * 0.35)
        key('spine', pitch * 0.5)
        key('chest', pitch * 0.5)
        key('head', float(p.get("head", 0.0)) * 0.8, float(p.get("head", 0.0)))
        swing = math.radians(24) * math.sin(ph) * walkp
        key('hip.L', swing - crouch * 1.5)
        key('hip.R', -swing - crouch * 1.5)
        key('knee.L', max(0.0, -swing) * 1.6 + crouch * 2.2)
        key('knee.R', max(0.0, swing) * 1.6 + crouch * 2.2)
        key('shoulder.L', -math.radians(13) * math.sin(ph) * walkp)
        key('shoulder.R', float(p.get("arm_r", math.radians(-18))))


def walk(rig, f0, f1, start, end, stride=0.85, swing=24.0):
    length = (Vector(end) - Vector(start)).length
    steps = max(2, int(length / stride * 12))
    for i in range(steps + 1):
        f = f0 + (f1 - f0) * i / steps
        t = i / steps
        pos = Vector(start).lerp(Vector(end), t)
        bob = 0.045 * math.sin(t * length / stride * 2 * math.pi * 2)
        rig.location = (pos.x, pos.y, pos.z + bob)
        rig.keyframe_insert('location', frame=f)

