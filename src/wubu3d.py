def cast_at(name, frame):
    """interpolated position of a cast member at a frame (for follow shots).
    Must honour the same holds as the rig, or the camera tracks where he would have
    been if he had not stopped."""
    c = CAST_POS[name]
    shift = 0.0
    for (a_, b_) in (c.get("hold") or []):
        if frame >= b_:
            shift += b_ - a_
        elif frame > a_:
            shift += frame - a_
    frame = frame - shift
    f0, f1 = c["walk"]
    t = 0.0 if frame <= f0 else 1.0 if frame >= f1 else (frame - f0) / max(1, (f1 - f0))
    a_, b_ = Vector(c["path"][0]), Vector(c["path"][1])
    p_ = a_.lerp(b_, t)
    return (p_.x, p_.y, c["z"])

