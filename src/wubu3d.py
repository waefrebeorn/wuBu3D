JSON_MODE = False

def main():
    global JSON_MODE
    ap = argparse.ArgumentParser(
        prog="wubu3d",
        description="WuBu3D — spec-to-film compiler. Agent commands: schema, validate, inspect, "
                    "plan, qa. Render paths: build, raster (C11, seconds), render/finish/make (Cycles).")
    ap.add_argument("cmd", choices=["build", "render", "finish", "make", "demo", "raster",
                                    "still", "validate", "inspect", "plan", "schema", "qa",
                                    "fetch", "clip"])
    ap.add_argument("spec", nargs="?", help="path to spec json ('-' or omitted reads stdin)")
    ap.add_argument("--preset", default="cartoon")
    ap.add_argument("--at", type=int, default=0, help="still: which frame to render")
    ap.add_argument("--raster", action="store_true", help="use the C11 rasteriser instead of Blender")
    ap.add_argument("--json", action="store_true",
                    help="one JSON object on stdout, human logs on stderr")
    a = ap.parse_args()
    real_stdout = sys.stdout
    if a.json:
        JSON_MODE = True
        sys.stdout = sys.stderr
    code, result = 0, {}
    try:
        if a.cmd == "clip":
            import wubu3d_gltf as _G
            asset = _G.load(PROJECT / a.spec if not Path(a.spec).is_absolute() else Path(a.spec))
            lo, hi = _G.bounds(asset)
            print(f"{asset.path.name}: {len(asset.primitives)} primitive(s), "
                  f"{len(asset.nodes)} node(s), {len(asset.skins)} skin(s)")
            print(f"bounds {lo.round(2).tolist()} .. {hi.round(2).tolist()}")
            for name in asset.clip_names():
                print(f"  {name:24s} {asset.clip_length(name):.3f}s")
            code = 0
        elif a.cmd == "fetch":
            result = fetch_asset(a.spec, list_only=(a.spec in (None, "-")))
            code = 0
        elif a.cmd in ("schema", "validate", "inspect", "plan", "qa"):
            result = run_agent_command(a.cmd, a.spec)
            code = 0 if result.get("ok") else 2
        elif a.cmd == "demo":
            spec_path = make_demo(a.preset)
            print(f"[wubu3d] demo spec -> {spec_path}")
            if a.raster:
                target = raster(spec_path)
            else:
                render(spec_path)
                target = finish(spec_path)
            print(f"[wubu3d] demo delivered -> {target}")
            result = {"ok": True, "spec": str(spec_path), "mp4": str(target)}
        else:
            if a.spec in (None, "-"):
                raw = json.load(sys.stdin)
                spec = wubu3d_spec.resolve(raw, DEFAULTS, PRESETS)
                tmp = PROJECT / "out" / spec["name"]
                tmp.mkdir(parents=True, exist_ok=True)
                spec_path = tmp / "stdin.spec.json"
                spec_path.write_text(json.dumps(raw, indent=1))
                print(f"[wubu3d] spec from stdin -> {spec_path}")
            else:
                spec_path = Path(a.spec)
            if a.cmd == "build":
                result = {"ok": True, "scene": str(build(spec_path))}
            elif a.cmd == "raster":
                result = {"ok": True, "mp4": str(raster(spec_path))}
            elif a.cmd == "still":
                result = {"ok": True, "still": str(still(spec_path, a.at))}
            elif a.cmd == "render":
                result = {"ok": True, "frames": str(render(spec_path))}
            elif a.cmd == "finish":
                result = {"ok": True, "mp4": str(finish(spec_path))}
            else:
                render(spec_path)
                result = {"ok": True, "mp4": str(finish(spec_path))}
    finally:
        if a.json:
            sys.stdout = real_stdout
            real_stdout.write(json.dumps(result, indent=1) + "\n")
    sys.exit(code)

if __name__ == "__main__":
    main()
