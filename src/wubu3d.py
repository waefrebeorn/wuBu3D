def denoise(spec: dict, out: Path) -> Path:
    src = out / "frames"
    dst = out / "denoised"
    dst.mkdir(exist_ok=True)
    if not spec.get("denoise") or not DENOISER.exists():
        return src
    pipe = (f'{FFMPEG} -y -v error -start_number 0 -i {src}/f_%04d.png '
            f'-f image2pipe -pix_fmt rgb24 -vcodec ppm - '
            f'| {DENOISER} --sigma 10 --scales 3 --keep 0.15 '
            f'| {FFMPEG} -y -v error -f image2pipe -pix_fmt rgb24 -vcodec ppm -i - '
            f'-start_number 0 {dst}/f_%04d.png')
    t0 = time.time()
    r = subprocess.run(["bash", "-o", "pipefail", "-c", pipe], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr[-800:]); return src
    print(f"[wubu3d] denoised {len(list(dst.glob('f_*.png')))} frames in {time.time()-t0:.0f}s")
    return dst

def grade(spec: dict, src: Path, out: Path) -> Path:
    import numpy as np
    from PIL import Image, ImageFilter
    from scipy.ndimage import median_filter

    dst = out / "graded"
    dst.mkdir(exist_ok=True)
    files = sorted(src.glob("f_*.png"))
    if not files:
        raise SystemExit("no frames to grade")
    horizon = np.array(spec["sky"]["horizon"], dtype=np.float32)
    zenith = np.array(spec["sky"]["zenith"], dtype=np.float32)
    t0 = time.time()
    _fonts = {}
    for i, f in enumerate(files):
        try:
            i = int(f.stem.split('_')[-1])   # a range render starts at frame N, not 0
        except ValueError:
            pass
        arr = np.asarray(Image.open(f).convert("RGBA"), dtype=np.float32) / 255
        rgb, alpha = arr[..., :3], arr[..., 3:4]
        h, w = rgb.shape[:2]
        yy = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
        sky = horizon * (1 - yy) ** 0.6 + zenith * yy ** 0.9
        rgb = rgb * alpha + sky * (1 - alpha)
        rgb = median_filter(rgb, size=(3, 3, 1))
        img = Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8))
        rgb = np.asarray(img.filter(ImageFilter.GaussianBlur(0.6)), dtype=np.float32) / 255

        lum = rgb.max(axis=2, keepdims=True)

        # halation: bright pass, wide blur, warm tint, screen blend. Not bloom —
        # bloom widens highlights, halation makes them read as light on film.
        hal_src = np.clip((lum - 0.70) / 0.30, 0, 1) * rgb
        hw, hh = max(2, w // 5), max(2, h // 5)
        hb = Image.fromarray((np.clip(hal_src, 0, 1) * 255).astype(np.uint8))
        hb = hb.resize((hw, hh), Image.BILINEAR).filter(ImageFilter.GaussianBlur(3.0))
        hal = np.asarray(hb.resize((w, h), Image.BILINEAR), dtype=np.float32) / 255
        hal = hal * np.array([1.0, 0.36, 0.16], dtype=np.float32)
        rgb = 1.0 - (1.0 - rgb) * (1.0 - 0.38 * hal)

        # bloom: tighter and cooler than the halation
        bright = np.clip((lum - 0.80) / 0.20, 0, 1) * rgb
        small = Image.fromarray((np.clip(bright, 0, 1) * 255).astype(np.uint8))
        small = small.resize((max(2, w // 10), max(2, h // 10)), Image.BILINEAR)
        small = small.filter(ImageFilter.GaussianBlur(1.8))
        bloom = np.asarray(small.resize((w, h), Image.BILINEAR), dtype=np.float32) / 255
        rgb = np.clip(rgb + float(spec.get("bloom", 0.18)) * bloom, 0, 1)

        # ACES (Narkowicz) — a neutral tone map, so the grade below is doing the look
        expo = float(spec.get("exposure", 1.05))
        if spec.get("tonemap") == "aces":
            # Unreal's order of operations: the tone curve belongs in LINEAR light, then the
            # display transform. Applied to sRGB-encoded values (the default here) the same
            # ACES fit crushes highlights and shifts hue; in linear, highlights roll off
            # instead of clipping, which is what makes a frame read as film rather than video.
            lin = np.where(rgb <= 0.04045, rgb / 12.92, ((rgb + 0.055) / 1.055) ** 2.4)
            x = np.clip(lin * expo, 0, None)
            y = (x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14)
            s = np.where(y <= 0.0031308, y * 12.92, 1.055 * np.power(y, 1.0 / 2.4) - 0.055)
            s = np.clip(s, 0, 1)
        else:
            x = np.clip(rgb * expo, 0, 1)
            s = np.clip((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14), 0, 1)

        # split tone: cool shadows, warm highlights
        l = s.max(axis=2, keepdims=True)
        shadow = np.clip(1.0 - l * 2.2, 0, 1)
        high = np.clip(l * 2.2 - 1.2, 0, 1)
        s = s + shadow * np.array([-0.012, 0.004, 0.030], dtype=np.float32)
        s = s + high * np.array([0.030, 0.012, -0.016], dtype=np.float32)

        # saturation is a knob, not a side effect: a scene can be graded moody without every
        # material collapsing to the same grey. 0.75 night desaturated 16% and the standing
        # order was "everything looks like clay" — the default was doing that.
        sat = float(spec.get("saturation", 1.12))
        grey = s.mean(axis=2, keepdims=True)
        s = np.clip(grey + (s - grey) * sat, 0, 1)
        # Purkinje shift: at night the eye desaturates and pulls toward blue-grey
        night = float(spec.get("night", 0.30))
        s = s * (1 - 0.22 * night) + grey * (0.22 * night)
        s = s + np.array([-0.004, 0.002, 0.014], dtype=np.float32) * night

        yv, xv = np.mgrid[0:h, 0:w]
        r = np.sqrt(((xv - (w - 1) / 2) / ((w - 1) / 2)) ** 2 +
                    ((yv - (h - 1) / 2) / ((h - 1) / 2)) ** 2) / math.sqrt(2)
        vig = np.clip(1 - 0.34 * r ** 2.4, 0, 1)[..., None]
        s = np.clip(s * vig, 0, 1)

        # grain after the tone map, weighted to the shadows, then triangular dither
        rng = np.random.default_rng(1000 + i)
        g = rng.standard_normal((h, w, 1), dtype=np.float32)
        gw = 0.020 * (0.35 + 0.65 * (1.0 - s.mean(axis=2, keepdims=True)))
        s = s + g * gw
        d = (rng.random((h, w, 1), dtype=np.float32) - rng.random((h, w, 1), dtype=np.float32))
        s = np.clip(s + d * (0.5 / 255.0), 0, 1)

        # cinema bars are for landscape frames: cropping a vertical frame to 2.39:1 hides
        # 76% of it, which is the whole picture the format exists for
        bar = int(max(0, (h - w / 2.39) / 2)) if w > h else 0
        if bar:
            s[:bar] = 0; s[-bar:] = 0

        # fades: multiply the whole frame by a ramp at each end
        fade = spec.get("fade") or {}
        fps = spec.get("fps", 24)
        n = len(files)
        mult = 1.0
        if fade.get("in"):
            mult *= min(1.0, i / max(1.0, fade["in"] * fps))
        if fade.get("out"):
            mult *= min(1.0, (n - 1 - i) / max(1.0, fade["out"] * fps))
        if mult < 1.0:
            s = s * mult

        frame_img = Image.fromarray((np.clip(s, 0, 1) * 255).astype(np.uint8))
        # captions: one word at a time, the format every vertical explainer uses. Either
        # a list of {text, in, out} or a pointer to a whisper-style words json
        # ([{word, start, end}]), which is what the transcription tools already emit.
        tlist = list(spec.get("titles") or [])
        caps = spec.get("captions")
        if isinstance(caps, dict) and caps.get("words"):
            wp_ = PROJECT / str(caps["words"])
            if wp_.exists():
                for wd in json.loads(wp_.read_text()):
                    wtext = wd.get("word") or wd.get("text") or ""
                    a_ = wd.get("start", wd.get("in"))
                    b_ = wd.get("end", wd.get("out"))
                    if wtext and isinstance(a_, (int, float)) and isinstance(b_, (int, float)):
                        tlist.append({"text": wtext, "in": float(a_), "out": float(b_),
                                      "size": caps.get("size", 0.048), "y": caps.get("y", 0.62),
                                      "pos": "center", "color": [0.97, 0.97, 0.97],
                                      "stroke": caps.get("stroke", True)})
            else:
                print(f"[wubu3d] captions file missing: {wp_}", file=sys.stderr)
        elif isinstance(caps, list):
            for c_ in caps:
                if not isinstance(c_, dict) or "text" not in c_:
                    continue
                t_ = dict(c_)
                t_.setdefault("size", 0.048); t_.setdefault("y", 0.62)
                t_.setdefault("pos", "center"); t_.setdefault("color", [0.97, 0.97, 0.97])
                t_.setdefault("stroke", True)
                tlist.append(t_)
        if tlist:
            from PIL import ImageDraw, ImageFont
            fp = FONT_PATH
            if str((spec.get("captions") or {}).get("font", "anton")).lower() in ("sans", "bold", "dejavu"):
                alt = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
                if alt.exists():
                    fp = alt
            dr = ImageDraw.Draw(frame_img)
            tsec = i / fps
            for t in tlist:
                if not (t.get("in", 0) <= tsec <= t.get("out", 1e9)):
                    continue
                size = int(t.get("size", 0.052) * h)
                if size not in _fonts:
                    try:
                        _fonts[size] = ImageFont.truetype(fp, size)
                    except Exception:
                        _fonts[size] = ImageFont.load_default()
                font = _fonts[size]
                text = t["text"]
                bb = dr.textbbox((0, 0), text, font=font)
                tw, th = bb[2] - bb[0], bb[3] - bb[1]
                px = {"left": 0.06, "center": 0.5, "right": 0.94}.get(t.get("pos", "center"), 0.5)
                x = int(w * px - tw * px)
                y = int(h * t.get("y", 0.80) - th / 2)
                col = tuple(int(c * 255) for c in t.get("color", [0.93, 0.90, 0.84]))
                sw = max(1, size // 16) if t.get("stroke") else 0
                if sw:
                    dr.text((x, y), text, font=font, fill=col,
                            stroke_width=sw, stroke_fill=(0, 0, 0))
                else:
                    dr.text((x + 2, y + 2), text, font=font, fill=(0, 0, 0))
                    dr.text((x, y), text, font=font, fill=col)
        frame_img.save(dst / f.name, compress_level=1)
        if i % 240 == 0:
            print(f"[wubu3d] graded {i}/{len(files)}", flush=True)
    print(f"[wubu3d] graded {len(files)} frames in {time.time()-t0:.0f}s")
    return dst

def score(spec: dict, out: Path) -> Path:
    import numpy as np
    import soundfile as sf

    sr, dur = 48000, spec["frames"] / spec["fps"]
    n = int(sr * dur)
    t = np.arange(n) / sr
    L = np.zeros(n); R = np.zeros(n)
    rng = np.random.default_rng(5)

    def add(sig, pan=0.0, gain=1.0):
        nonlocal L, R
        L += sig * gain * math.sqrt((1 - pan) / 2)
        R += sig * gain * math.sqrt((1 + pan) / 2)

    def place(seg, at):
        o = np.zeros(n); i = int(at * sr); e = min(n, i + len(seg))
        if e > i: o[i:e] = seg[:e - i]
        return o

    wind = rng.standard_normal(n)
    # the smoothing kernel must be odd and no longer than the buffer: a 4,001-sample
    # kernel on a 4,000-sample buffer made np.convolve return 4,001 and the wind LFO
    # broadcast against a 4,000-sample time base — every film under ~0.2 s died here
    klen = max(3, min(4001, n if n % 2 else n - 1))
    k = np.hanning(klen); k /= k.sum()
    wind = np.convolve(wind, k, mode="same")[:n]
    add(wind * spec["sound"].get("wind", 0.05) * (0.6 + 0.4 * np.sin(2 * np.pi * 0.06 * t)))

    cue = spec["sound"].get("cue", 0.6) * dur
    motif = spec["sound"].get("motif", [220, 261.6, 329.6])
    # diegetic hits. A "why does he..." explainer lives on the sound of the thing being
    # done — locks clicking, metal clinking, weight landing — not on a music bed. Each is
    # synthesised: a noise transient plus a short ring, weighted by the material.
    def sfx(name, at, gain=0.5, pan=0.0):
        if name == "clink":          # small metal parts: bright, fast, two rings
            ln = int(0.30 * sr); tt = np.arange(ln) / sr
            ring = (np.sin(2*np.pi*2450*tt) * 0.5 + np.sin(2*np.pi*3700*tt) * 0.3
                    + np.sin(2*np.pi*5200*tt) * 0.12)
            sig = ring * np.exp(-tt / 0.055)
        elif name == "click":        # a lock snapping shut: louder transient, tighter
            ln = int(0.18 * sr); tt = np.arange(ln) / sr
            sig = (np.sin(2*np.pi*1250*tt) * 0.6 + np.sin(2*np.pi*3100*tt) * 0.25) * np.exp(-tt / 0.022)
        elif name == "thud":         # something heavy placed on wood
            ln = int(0.55 * sr); tt = np.arange(ln) / sr
            sig = np.sin(2*np.pi*72*tt) * np.exp(-tt / 0.13) + 0.25*np.sin(2*np.pi*46*tt)*np.exp(-tt/0.2)
        elif name == "scrape":       # dragging metal across stone
            ln = int(0.45 * sr); tt = np.arange(ln) / sr
            nz = np.random.default_rng(3).standard_normal(ln)
            k = np.hanning(64); nz = np.convolve(nz, k, mode="same")[:ln]
            sig = nz * 0.5 * np.exp(-tt / 0.22) * (0.6 + 0.4*np.sin(2*np.pi*17*tt))
            sig = np.convolve(sig, np.hanning(9)/np.hanning(9).sum(), mode="same")[:ln]
        else:
            return
        # 4 ms noise transient on top of every hit — that is the "contact"
        nl = int(0.004 * sr)
        tr = np.random.default_rng(11).standard_normal(nl) * np.linspace(1.0, 0.0, nl)
        sig[:nl] += tr
        add(place(sig * gain, at), pan=pan)

    for hit in (spec.get("sound", {}).get("sfx") or []):
        if isinstance(hit, dict) and "at" in hit:
            sfx(hit.get("type", "clink"), float(hit["at"]), float(hit.get("gain", 0.45)),
                float(hit.get("pan", 0.0)))

    def play(freqs, at, gain=0.10, d=0.9, pan=0.0):
        for i, f in enumerate(freqs):
            st = np.arange(int(d * sr)) / sr
            s = (np.sin(2 * np.pi * f * st) * 0.6 + np.sin(4 * np.pi * f * st) * 0.2) * np.exp(-st / 0.55)
            add(place(s * gain, at + i * 0.55), pan=pan)
    for at, g in ((dur * 0.06, 0.10), (dur * 0.28, 0.075), (dur * 0.5, 0.05)):
        if at < cue: play(motif, at, gain=g, pan=-0.2 if at < cue / 2 else 0.2)

    swell = np.clip((t - dur * 0.25) / max(0.1, cue - dur * 0.25), 0, 1) ** 1.5
    drift = sum(np.sin(2 * np.pi * f * t) * a for f, a in ((55, 0.30), (82.5, 0.18), (110, 0.10)))
    add(drift * swell * 0.9)

    ln = int(2.6 * sr); tt = np.arange(ln) / sr
    add(place(np.sin(2 * np.pi * np.geomspace(80, 28, ln) * tt) * np.exp(-tt / 1.0) * 0.7, cue))
    burst = rng.standard_normal(ln) * np.exp(-tt / 0.2)
    bh = np.hanning(2001); bh /= bh.sum()
    add(place(np.convolve(burst, bh, mode="same") * 0.25, cue))
    play(motif, cue + 0.8, gain=0.08, d=2.0, pan=0.1)

    post = np.zeros(n); i0 = int((cue + 0.6) * sr)
    if i0 < n:
        a_ = np.minimum(1.0, np.arange(n - i0) / (1.5 * sr))
        post[i0:] = a_ * np.exp(-np.arange(n - i0) / (sr * 8.0))
    for f, amp, pan in ((220, 0.10, -0.3), (277.2, 0.07, 0.3), (330, 0.06, -0.1), (440, 0.05, 0.2)):
        add(np.sin(2 * np.pi * f * t) * amp * post, pan=pan)

    fade = np.clip(t / 1.2, 0, 1) * np.clip((dur - t) / max(0.6, dur * 0.06), 0, 1)
    L *= fade; R *= fade
    mix = np.tanh(np.stack([L, R], 1) * 1.2)
    mix *= 0.70 / (np.abs(mix).max() + 1e-9)
    path = out / "score.wav"
    sf.write(path, mix.astype(np.float32), sr)
    print(f"[wubu3d] score {dur:.1f}s -> {path.name}")
    return path

def mux(spec: dict, frames_dir: Path, wav: Path, out: Path) -> Path:
    w, h = spec["resolution"]
    ew, eh = (w // 2) * 2, (h // 2) * 2
    if (ew, eh) != (w, h):
        ew, eh = w + (w % 2), h + (h % 2)
    target = out / f"{spec['name']}.mp4"
    # deliver at native resolution. A silent 2x upscale used to live here, which made
    # every file claim twice the resolution it was rendered at — the exact kind of
    # number this project is supposed to be able to defend. Ask for it explicitly.
    mult = int(spec.get("upscale", 1))
    cmd = [FFMPEG, "-y", "-v", "error", "-framerate", str(spec["fps"]), "-start_number", "0",
           "-i", str(frames_dir / "f_%04d.png"), "-i", str(wav)]
    if mult > 1:
        cmd += ["-vf", f"scale={ew * mult}:{eh * mult}:flags=lanczos"]
    cmd += ["-c:v", "libx264", "-preset", "slow", "-crf", "21", "-pix_fmt", "yuv420p",
            "-tune", "film", "-c:a", "aac", "-b:a", "160k", "-shortest",
            "-movflags", "+faststart", str(target)]
    subprocess.run(cmd, check=True)
    size = target.stat().st_size / 1e6
    print(f"[wubu3d] delivered {target.name}  {size:.1f} MB")
    return target

